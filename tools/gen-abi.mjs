// Regenerates TS ABI files for web/ from Foundry build output. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";
const pick = (n) => JSON.parse(readFileSync(`out/${n}.sol/${n}.json`, "utf8")).abi;
const src =
  `// AUTO-GENERATED by tools/gen-abi.mjs - do not edit\n` +
  `export const slipGuardVaultAbi = ${JSON.stringify(pick("SlipGuardVault"), null, 2)} as const;\n\n` +
  `export const slipGuardVaultFactoryAbi = ${JSON.stringify(pick("SlipGuardVaultFactory"), null, 2)} as const;\n\n` +
  `export const mockUsdcAbi = ${JSON.stringify(pick("MockUSDC"), null, 2)} as const;\n`;
writeFileSync("web/src/abi.ts", src);
console.log("wrote web/src/abi.ts");
